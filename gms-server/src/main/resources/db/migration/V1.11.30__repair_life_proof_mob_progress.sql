CREATE TEMPORARY TABLE _bd_lp_started AS
SELECT qs.queststatusid,
       qs.characterid,
       qs.quest AS quest_id,
       COALESCE(MAX(CASE
           WHEN qp.progressid = 0 AND qp.progress REGEXP '^[0-9]+$'
               THEN CAST(qp.progress AS UNSIGNED)
           ELSE 0
       END), 0) AS legacy_progress
FROM queststatus qs
JOIN (SELECT DISTINCT quest_id FROM _bd_lp_mob_targets) t ON t.quest_id = qs.quest
LEFT JOIN questprogress qp ON qp.queststatusid = qs.queststatusid
WHERE qs.status = 1
GROUP BY qs.queststatusid, qs.characterid, qs.quest;

CREATE TEMPORARY TABLE _bd_lp_existing AS
SELECT s.queststatusid,
       qp.progressid,
       COALESCE(MAX(CASE
           WHEN qp.progress REGEXP '^[0-9]+$' THEN CAST(qp.progress AS UNSIGNED)
           ELSE 0
       END), 0) AS progress
FROM _bd_lp_started s
JOIN questprogress qp ON qp.queststatusid = s.queststatusid
JOIN _bd_lp_mob_targets t ON t.quest_id = s.quest_id AND t.progress_id = qp.progressid
GROUP BY s.queststatusid, qp.progressid;

CREATE TEMPORARY TABLE _bd_lp_shared AS
SELECT s.queststatusid,
       t.quest_id,
       LEAST(MAX(t.required_count), GREATEST(s.legacy_progress, COALESCE(MAX(e.progress), 0))) AS progress
FROM _bd_lp_started s
JOIN _bd_lp_mob_targets t ON t.quest_id = s.quest_id
LEFT JOIN _bd_lp_existing e ON e.queststatusid = s.queststatusid AND e.progressid = t.progress_id
WHERE t.shared_progress = 1
GROUP BY s.queststatusid, t.quest_id, s.legacy_progress;

CREATE TEMPORARY TABLE _bd_lp_next AS
SELECT s.characterid,
       s.queststatusid,
       t.progress_id,
       CASE
           WHEN t.shared_progress = 1 THEN sh.progress
           ELSE LEAST(t.required_count, GREATEST(s.legacy_progress, COALESCE(e.progress, 0)))
       END AS progress
FROM _bd_lp_started s
JOIN _bd_lp_mob_targets t ON t.quest_id = s.quest_id
LEFT JOIN _bd_lp_existing e ON e.queststatusid = s.queststatusid AND e.progressid = t.progress_id
LEFT JOIN _bd_lp_shared sh ON sh.queststatusid = s.queststatusid AND sh.quest_id = t.quest_id;

DELETE qp
FROM questprogress qp
JOIN _bd_lp_started s ON s.queststatusid = qp.queststatusid;

INSERT INTO questprogress (characterid, queststatusid, progressid, progress)
SELECT characterid,
       queststatusid,
       progress_id,
       LPAD(progress, 3, '0')
FROM _bd_lp_next
WHERE progress > 0;

DROP TEMPORARY TABLE IF EXISTS _bd_lp_next;
DROP TEMPORARY TABLE IF EXISTS _bd_lp_shared;
DROP TEMPORARY TABLE IF EXISTS _bd_lp_existing;
DROP TEMPORARY TABLE IF EXISTS _bd_lp_started;
DROP TEMPORARY TABLE IF EXISTS _bd_lp_mob_targets;
